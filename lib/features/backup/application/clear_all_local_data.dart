import 'package:drift/drift.dart' show TableInfo;
import 'package:localfit_ai/data/database/app_database.dart';
import 'package:localfit_ai/data/database/tables.dart'
    show Foods, FoodAliases, FoodNutritionRevisions, FoodPortions, FoodEvidence;
import 'package:localfit_ai/features/ai_conversation/domain/chat_image.dart';
import 'package:localfit_ai/features/campus_menus/domain/menu_raw_content_store.dart';
import 'package:localfit_ai/features/food_scan/domain/meal_image.dart';

/// Deletes every logical row from the local database, children first so
/// foreign keys stay satisfied, then removes cached media files, imported
/// menu raw text, and AI credentials from secure storage. Used by the danger
/// zone and by restore (which skips the byte sweeps because a restore is not
/// a wipe).
///
/// 2.0 invariant: a full clear must leave no user-controlled bytes anywhere —
/// database rows, temporary meal-scan images, chat images, imported menu 原文,
/// the AI API key. The SQLCipher database key itself is intentionally preserved
/// (or regenerated by the caller): deleting it without recreating the database
/// would corrupt the local store on next launch.
///
/// **例外（2026-10-23 用户）**：内置食物库（随包目录 + CSV 导入行）不是用户
/// 字节，`clear()` **保留**它们——导入行也属内置，只有 App 内新建的才是自建。
/// 要清内置食物，走设置页的「清空内置食物」（`ClearBuiltinFoods`）。
/// [clearDatabaseRowsOnly]（恢复流程）仍是全清：备份自带食物表，留着会撞主键。
final class ClearAllLocalData {
  const ClearAllLocalData(
    this.database, {
    this.temporaryMealImageStore,
    this.menuRawContentStore,
    this.apiKeyStore,
    this.chatImageStore,
    this.dishImageStore,
    this.avatarImageStore,
  });

  final AppDatabase database;
  final TemporaryMealImageStore? temporaryMealImageStore;
  final MenuRawContentStore? menuRawContentStore;
  final AiApiKeyStoreRef? apiKeyStore;

  /// AI 对话页的图片副本（docs/21 §5.7）。它不是数据库行，必须显式整目录
  /// 删除，否则「清除全部本地数据」会留下聊天图片。
  final ChatImageStore? chatImageStore;

  /// 食堂菜品照片（docs/29 §P7 需求 16）。同样是文件不是行：只清库会留下
  /// 用户拍的每一张菜品照片（2026-10-08 缺陷排查补齐）。
  final DishImageStoreRef? dishImageStore;

  /// 头像副本同样是私有文件：清库后不再有路径可查，必须整目录删除。
  final AvatarImageStoreRef? avatarImageStore;

  Future<void> clear() async {
    await database.transaction(() async {
      await database.delete(database.workoutSets).go();
      await database.delete(database.workoutSessions).go();
      await database.delete(database.plannedExercises).go();
      await database.delete(database.workoutDays).go();
      await database.delete(database.workoutPlans).go();
      await database.delete(database.mealItems).go();
      await database.delete(database.meals).go();
      // 2026-10-23 用户：「清除本地数据不清内置食物；导入的食物都属内置，
      // 只有 App 内新建才是自建」。内置食物（随包目录 + CSV 导入）是应用
      // 数据，不是用户字节：这里只删**自建**食物及其派生行；内置行的
      // 别名/修订/份量原样保留（`FoodEvidence` 是目录级证据，没有 foodId，
      // 整表保留）。
      await _deleteUserCreatedFoods();
      await database.delete(database.foodImportJobs).go();
      // Menu v1（2.0-3）：菜单链按 campus -> item 顺序显式删除。
      await database.delete(database.menuItemNutritionEvidence).go();
      await database.delete(database.menuItemFoodMatches).go();
      await database.delete(database.menuItems).go();
      await database.delete(database.menuServices).go();
      await database.delete(database.menuSnapshots).go();
      await database.delete(database.menuImportJobs).go();
      await database.delete(database.menuSources).go();
      await database.delete(database.venues).go();
      await database.delete(database.campusProfiles).go();
      // Planning v1（2.0-4）：候选子表在前。
      await database.delete(database.dailyPlanCandidates).go();
      await database.delete(database.dailyPlanSlots).go();
      await database.delete(database.dailyPlans).go();
      await database.delete(database.availabilityWindows).go();
      await database.delete(database.exercises).go();
      await database.delete(database.dailyTargets).go();
      await database.delete(database.goals).go();
      await database.delete(database.measurements).go();
      await database.delete(database.aiProviderConfigs).go();
      await database.delete(database.profiles).go();
      // 上面是按外键链人工排出的顺序；下面这轮兜底把**其余所有表**一并
      // 清空（重复删除空表无害）。schema 17 新增的 7 张表曾整批漏在这里：
      // 全清必须覆盖全部表，不能依赖人工维护清单（docs/21 §5.8.1）。
      //
      // 食物五表例外：内置食物要活过「清除所有数据」（2026-10-23 用户），
      // 而兜底循环会无差别清空——必须显式跳过。
      for (final table in database.allTables) {
        if (_isPreservedFoodTable(table)) continue;
        await database.delete(table).go();
      }
    });
    // 数据库行删除成功后才清理外围字节。失败在这里不回滚数据库（行已
    // 确认删除，把旧图片/原文/Key 留下比半重试状态更安全），由调用方提示。
    // 注意是 clearAll 不是 clearStale：全清承诺「不留任何用户字节」，
    // clearStale 的保留窗口会放过用户刚拍的餐照。
    await temporaryMealImageStore?.clearAll();
    // 导入菜单的原文不在数据库里（只存相对路径），必须显式整目录删除，
    // 否则「清除全部本地数据」会留下菜单原文。
    await menuRawContentStore?.clearAll();
    // 聊天图片同理：它是聊天消息的副本，不在数据库里。
    await chatImageStore?.clearAll();
    // 菜品照片同理：食堂菜品行删掉之后照片文件仍然在私有目录里躺着。
    await dishImageStore?.clearAll();
    await avatarImageStore?.clearAll();
    await apiKeyStore?.clear();
  }

  /// 内置食物及其派生表：`clear()` 的兜底循环要跳过它们。
  ///
  /// `FoodEvidence` 没有 `foodId`（目录级证据），整表保留；另外三张有
  /// `foodId` 的派生表只删自建食物那一部分（见 [_deleteUserCreatedFoods]）。
  bool _isPreservedFoodTable(TableInfo table) =>
      table is Foods ||
      table is FoodAliases ||
      table is FoodNutritionRevisions ||
      table is FoodPortions ||
      table is FoodEvidence;

  /// 只删**自建**食物（`is_user_created = 1`）及其派生行；内置行一条不动。
  ///
  /// 派生表虽然声明了 cascade，这里仍显式按 `foodId` 删：内置行的派生数据
  /// 必须留下，不能靠「整表清空」的旧写法。
  Future<void> _deleteUserCreatedFoods() async {
    final userIds = database.selectOnly(database.foods)
      ..addColumns([database.foods.id])
      ..where(database.foods.isUserCreated.equals(true));
    await (database.delete(
      database.foodAliases,
    )..where((row) => row.foodId.isInQuery(userIds))).go();
    await (database.delete(
      database.foodNutritionRevisions,
    )..where((row) => row.foodId.isInQuery(userIds))).go();
    await (database.delete(
      database.foodPortions,
    )..where((row) => row.foodId.isInQuery(userIds))).go();
    await (database.delete(
      database.foods,
    )..where((row) => row.isUserCreated.equals(true))).go();
  }

  /// 清空数据库行但保留媒体文件、菜单原文和 AI Key：恢复流程在同一个事务
  /// 里重写数据，外围字节不属于备份内容，不应被清掉。
  Future<void> clearDatabaseRowsOnly() async {
    await database.transaction(() async {
      await database.delete(database.workoutSets).go();
      await database.delete(database.workoutSessions).go();
      await database.delete(database.plannedExercises).go();
      await database.delete(database.workoutDays).go();
      await database.delete(database.workoutPlans).go();
      await database.delete(database.mealItems).go();
      await database.delete(database.meals).go();
      await database.delete(database.foodAliases).go();
      await database.delete(database.foodNutritionRevisions).go();
      await database.delete(database.foodPortions).go();
      await database.delete(database.foodEvidence).go();
      await database.delete(database.foodImportJobs).go();
      // Menu v1（2.0-3）：菜单链按 campus -> item 顺序显式删除。
      await database.delete(database.menuItemNutritionEvidence).go();
      await database.delete(database.menuItemFoodMatches).go();
      await database.delete(database.menuItems).go();
      await database.delete(database.menuServices).go();
      await database.delete(database.menuSnapshots).go();
      await database.delete(database.menuImportJobs).go();
      await database.delete(database.menuSources).go();
      await database.delete(database.venues).go();
      await database.delete(database.campusProfiles).go();
      // Planning v1（2.0-4）：候选子表在前。
      await database.delete(database.dailyPlanCandidates).go();
      await database.delete(database.dailyPlanSlots).go();
      await database.delete(database.dailyPlans).go();
      await database.delete(database.availabilityWindows).go();
      await database.delete(database.exercises).go();
      await database.delete(database.foods).go();
      await database.delete(database.dailyTargets).go();
      await database.delete(database.goals).go();
      await database.delete(database.measurements).go();
      await database.delete(database.aiProviderConfigs).go();
      await database.delete(database.profiles).go();
      // 与 clear() 同一口径：人工顺序 + 全表兜底（漏表会让「恢复」之后
      // 旧数据混进来）。
      for (final table in database.allTables) {
        await database.delete(table).go();
      }
    });
  }
}

/// Minimal dependency-facing surface of [AiApiKeyStore] so this application
/// layer does not depend on the settings data layer just to delete a key.
abstract interface class AiApiKeyStoreRef {
  Future<void> clear();
}

/// 同上：只依赖「能整目录清掉菜品照片」这一点，不依赖 campus_menus 数据层。
abstract interface class DishImageStoreRef {
  Future<void> clearAll();
}

/// 头像整目录清理口：应用层不依赖 settings 的文件存储实现。
abstract interface class AvatarImageStoreRef {
  Future<void> clearAll();
}
