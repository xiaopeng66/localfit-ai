/// | 餐次按用户说的；同名食物合并；用户点到的每样都要列全 | 记错餐次/漏食物 |
/// | 饮食偏好与忌口是硬约束 | 推荐/记录违忌口食物 |
/// | 步数是系统读的；「今天走了一万步」不是改步数目标 | 编译器可能把事实写成 `targets.update` |
/// | 食物来源优先级；今天已有的餐别重复记 | 重复记一餐、用错库 |
/// | 设置/API Key 永远不能通过对话修改 | 内容承诺改设置，实际没有入口 |
