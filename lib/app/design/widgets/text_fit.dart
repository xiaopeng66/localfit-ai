import 'package:flutter/material.dart';

/// 并排布局的**字号自适应判据**（今日页三块卡片共用，docs/27 §6）。
///
/// 为什么需要它：设计稿（`ui设计/pages/*.html`）**没有任何断点**，圆环在左 /
/// 宏量条在右、三格趋势、两格统计都是恒定的并排形态。旧代码用常量
/// `constraints.maxWidth < 300` 判定能否并排，而 360dp 手机上卡片内宽恰好
/// 296dp，于是**主流手机一律被降级成竖排**——这正是用户 2026-10-03 报告的
/// 「我的 app 安装以后今日热量卡片不一样」（证据：docs/evidence/
/// 2026-10-03-ui-display-review.md 附录 D）。
///
/// 为什么不照抄设计稿的断点：设计稿在 320px 宽度下**自身就会裁掉数值**
/// （无头渲染实证，`E:/AI/Zcode/tmp/cal-320-2x.png`），所以 320px 不是设计
/// 支持的宽度，退化时机只能由实现决定。
///
/// 为什么不用 `TextPainter` 实测字形宽度：测试环境（flutter_test）用 Ahem
/// 字体，每个字符都按一个全角字宽上报，实测值约为真机 Roboto 的两倍，
/// 会把「1.0× 下明明放得下」判成放不下（本判据的 360dp 回归测试最初就是
/// 这么红的）。改用**纯算术预算**后，测试与真机结论一致。
///
/// 判据 = `available >= baseNeed × 当前字号倍率`，[baseNeed] 是设计稿在
/// 1.0× 字号下并排所需的内容宽度，由各调用点按设计稿文字规格推出（算式写在
/// 调用点注释里，[LfRowBudgets] 存共用值）。
bool fitsRow(
  BuildContext context, {
  required double available,
  required double baseNeed,
}) => available >= baseNeed * bodyTextScale(context);

/// 正文字号（12px）处的系统字号倍率。
///
/// Android 的非线性字号下 `MediaQuery.textScalerOf(context).scale(1)` 返回的
/// 倍数与实际正文放大不一致，取 12px 处的比值才与排版相符。
double bodyTextScale(BuildContext context) =>
    MediaQuery.textScalerOf(context).scale(12) / 12;

/// 三块卡片的 1.0× 内容预算（单位 dp，均为**纯算术推导**而非实测像素）。
///
/// 判据比较的是 [LayoutBuilder] 拿到的 `constraints.maxWidth`，所以预算值要按
/// **各调用点实际看得见的宽度**来定，两类宽度必须落在判据两侧：
///
/// | 卡片 | 可见宽度 = 视口 − | 360dp | 320dp | 预算 |
/// |---|---|---|---|---|
/// | 热量卡 / 趋势三格（卡内） | 页面 32 + 卡片 32 = 64 | 296 | 256 | 290 |
/// | 饮水 / 步数两格（页面级） | 页面 32 | 328 | 288 | 300 |
///
/// 为什么 320dp 要竖排而不是并排：设计稿在 320px 宽度下**自身就会裁字/裁格**
/// （热量卡的「156 / 200 g」被裁、饮水/步数第二格被裁，无头渲染实证
/// `E:/AI/Zcode/tmp/cal-320-2x.png` 与 `qs-320-2x.png`），所以 320px 不是设计
/// 支持的宽度；实现必须在此时退化。既有决策（`bento_layout_test` 的三条
/// 320dp 用例）也是这个口径，预算值与该口径对齐以免互相打架。
abstract final class LfRowBudgets {
  /// 热量卡（卡内）：圆环 120 + 间隙 16 + 文字列 ≈ 140 = 276，取 290。
  ///
  /// 文字列 = 圆点 8 + 间隙 6 + 最宽标签「碳水化合物」(5 个 CJK @12px = 60)
  /// + 最宽数值串「156 / 200 g」(11 个半角 @12px ≈ 66)。右侧占比行三格
  /// （`蛋白 30%`）不是约束项。290 落在 320dp(256) 与 360dp(296) 之间。
  static const double calorieCard = 290;

  /// 趋势三格（卡内）：每格 85 + 两处 `gap-2.5`(10) = 275，取 290。
  ///
  /// 85 = MutedBlock 内边距 12×2 + 数值行（16px 数值 + 10px 单位 ≈ 55）。
  static const double trendTiles = 290;

  /// 饮水 / 步数两格（页面级，不套卡片）：每格 132 + `gap-3`(12) = 276，取 300。
  ///
  /// 132 = DesignCard 内边距 16×2 + 首行（图标 14 + 间隙 6 + 「饮水」24 +
  /// 状态串「达标 100%」≈ 48）= 124，取 132 留余量。
  /// 300 落在 320dp(288) 与 360dp(328) 之间。
  static const double quickStats = 300;

  /// 热量卡脚注（卡内，A `.energy-foot` 的两端一行）：左「目标 9,999 kcal」
  /// 87 + 右「还可摄入 9,999 kcal」109 + 两端间隔 8 = 204，取 232。
  ///
  /// 87 = 「目标 」2 CJK + 空格 @11px(≈27) + 「9,999」5 半角(30) + 「 kcal」(30)；
  /// 109 = 「还可摄入 」4 CJK + 空格(49) + 「9,999」(30) + 「 kcal」(30)。
  /// 232 落在 320dp(252) 与 360dp×1.5× 的 348 之间：1.0× 下两端一行（A 的
  /// 形态），大字号下竖排。
  static const double energyFoot = 232;

  /// 体重卡 caption（卡内）：值「168.5 kg」≈ 95 + 间隔 12 + 右列最短可用宽
  /// （「最近记录 ↓ 1.2」≈ 86）= 193，取 205。
  ///
  /// 右列本来就可省略（`ellipsis`），真正的约束是**值必须整条单行**——
  /// 2.0× / 320dp 实测值单独就要 245dp，与 12dp 间隔相加超过卡内 252dp
  /// （round7 2A：`dashboard_weight_card` 的 caption Row 溢出 0.99px，
  /// 要夹具喂了体重数据才暴露）。205 落在 320dp(252) 与 360dp×1.5×(307)
  /// 之间：1.0× 并排、大字号下值占一行、注在下一行。
  static const double weightCaption = 205;

  /// 记录页 hero 进度条口径行（页面级宽 288）：左「已完成 100%」65 + 右
  /// 「目标 10,000 kcal」85 + 最小间隔 8 = 158，取 200。
  ///
  /// 65 = 3 CJK @10px(micro, 30) + 空格(5) + 「100%」4 半角(20)，留到 999%；
  /// 85 = 2 CJK(20) + 空格 + 五位数(30) + 「 kcal」(25)。
  /// 200 落在 320dp(288) 与 320dp×1.5×(300) 之间：1.0× 两端一行（设计形态），
  /// 1.5× 起竖排。这条兜底是 round7 2A 门禁逼出来的——旧夹具没有目标，
  /// 比例块（条 + 这行口径）整块不渲染，2.0× 下的溢藏在了「没数据」后面。
  static const double heroBarCaption = 200;

  /// 今日页「下一餐」预算卡的值行（卡内，A `.budget-line` 的两端一行）：
  /// 取值最大的两种组合之一 —— 有目标：值「9,999 kcal」（22px 数值 ≈ 60 +
  /// 12px「 kcal」≈ 26 = 86）+ 间隔 8 + 注「今日剩余额度」6 CJK @12px(72) =
  /// 166；未设目标：值「— kcal」36 + 8 + 注「尚未设定热量目标」8 CJK(96) = 140。
  /// 取 166 上浮到 190。
  ///
  /// 190 落在 320dp(288) 与 320dp×1.5×(285) 之下、320dp×1.732×(329) 之上：
  /// 1.0×/1.5× 并排（真字形 1.5× 需 249dp），更大字号竖排。
  /// 这条兜底是 round7 2A 整页渲染审看逼出来的——旧件（值 `Expanded` +
  /// 注 `Flexible`）把一行劈两半，2.0× 下 `ellipsis` 静默把「1,275 kcal」
  /// 裁成「1,2…」，而溢出收集器**不会报**（省略号不抛 RenderFlex）。
  static const double nextMealLine = 190;

  /// 食物库结果头（页面级宽 328/288，A `app.js:195` 的
  /// `.section-title.with-link` 两端一行）：左「49,465 种食物」+ 右
  /// 「kcal / 100g」。
  ///
  /// 左端是**变长**的（六位数带千分位）：9 个半角(59) + 空格(4) + 3 CJK(36)
  /// = 99；右端 11 个半角(68)；最小间隔 8 ⇒ 175，取 200 上浮。
  ///
  /// 200 落在 320dp(288) 与 360dp×1.5×(300) 之下：1.0× 两端一行（A 的形态）、
  /// 1.5× 起竖排（左端在上、单位在下，都左对齐——与今日页两张卡同款降级）。
  /// 这条兜底是 round7 阶段 3 的 far-jump 测试逼出来的：
  /// `A RenderFlex overflowed by 60 pixels on the right`（2.0× 的两端行）。
  static const double foodResultsHeader = 200;
}
